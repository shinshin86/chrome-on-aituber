function repositoryUrl(repository, homepage) {
  const value = typeof repository === "string" ? repository : repository?.url;

  if (value) {
    const normalized = value
      .replace(/^git\+/, "")
      .replace(/^git:\/\//, "https://")
      .replace(/\.git$/, "");

    if (/^[\w.-]+\/[\w.-]+$/.test(normalized)) {
      return `https://github.com/${normalized}`;
    }

    return normalized;
  }

  return homepage ?? "Not specified";
}

async function findLicenseText(packageDirectory, packageJson) {
  const fileNames = await readdir(packageDirectory);
  const licenseFile = fileNames
    .filter((fileName) => /^(licen[cs]e|copying)(\..*)?$/i.test(fileName))
    .sort((left, right) => left.localeCompare(right))[0];

  if (licenseFile) {
    return readFile(resolve(packageDirectory, licenseFile), "utf8");
  }

  if (packageJson.license === "MIT") {
    const attribution = packageJson.author
      ? `Package author: ${typeof packageJson.author === "string" ? packageJson.author : packageJson.author.name}\n\n`
      : "";
    return `${attribution}The published package declares the MIT license but does not include a separate license file. The standard MIT license text follows.\n\n${MIT_LICENSE_FALLBACK}`;
  }

  throw new Error(
    `No license text found for ${packageJson.name}@${packageJson.version}`,
  );
}

const packageLock = JSON.parse(await readFile(packageLockPath, "utf8"));
const notices = new Map();

for (const [packagePath, lockEntry] of Object.entries(
  packageLock.packages ?? {},
)) {
  if (!packagePath || lockEntry.dev) continue;

  const packageDirectory = resolve(projectRoot, packagePath);
  const packageJson = JSON.parse(
    await readFile(resolve(packageDirectory, "package.json"), "utf8"),
  );
  const key = `${packageJson.name}@${packageJson.version}`;

  if (notices.has(key)) continue;

  notices.set(key, {
    key,
    license: packageJson.license ?? lockEntry.license ?? "Not specified",
    repository: repositoryUrl(packageJson.repository, packageJson.homepage),
    text: (await findLicenseText(packageDirectory, packageJson)).trim(),
  });
}

const entries = [...notices.values()].sort((left, right) =>
  left.key.localeCompare(right.key),
);
const separator = "=".repeat(80);
const body = entries
  .map(
    ({ key, license, repository, text }) =>
      `${separator}\n${key}\nLicense: ${license}\nSource: ${repository}\n${separator}\n\n${text}`,
  )
  .join("\n\n");
const output = `NPM PRODUCTION DEPENDENCY THIRD-PARTY NOTICES

Generated from package-lock.json by npm run licenses:generate.
Do not edit this file manually.

Packages included: ${entries.length}

${body}
`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, output, "utf8");

console.log(`Wrote ${entries.length} package notices to public/licenses/NPM-THIRD-PARTY-NOTICES.txt`);
